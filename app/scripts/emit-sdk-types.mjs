#!/usr/bin/env node
// The types of @cxxi-lab/hubbyware-sdk (packages/hubbyware-sdk/types/index.d.ts): the SDK's common API, the one a
// hubby has in its frame (packages/hubbyware-sdk/frame/common.ts, docs/plan-isolation.md § 2), in one declaration
// file, the design system and npm packages left as imports. A hubby's repository builds against them; at run time
// its frame's runtime provides the SDK.
//   node scripts/emit-sdk-types.mjs           writes them
//   node scripts/emit-sdk-types.mjs --check   fails when they are not up to date (CI)
import { execFileSync } from 'node:child_process'
import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { createRequire } from 'node:module'

const APP = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const OUT = resolve(APP, '../packages/hubbyware-sdk/types/index.d.ts')
const CHECK = process.argv.includes('--check')
// in the app (not in node_modules: the bundler would take it for a library), so the declarations
// find the packages (react…) as the sources do
const WORK = join(APP, '.cache/sdk-types')
const bin = name => join(APP, '../node_modules/.bin', name)

rmSync(WORK, { recursive: true, force: true })
mkdirSync(WORK, { recursive: true })
// 1. the SDK's declarations, 2. the design system's (reached through node_modules), 3. bundled from its entry
const SDK = resolve(APP, '../packages/hubbyware-sdk')
execFileSync(bin('tsc'), ['-p', SDK, '--noEmit', 'false', '--declaration', '--emitDeclarationOnly', '--rootDir', SDK, '--outDir', join(WORK, 'decl')], { stdio: 'inherit' })
// (its entry, src/index.ts: the package exports no ./package.json)
const ui = dirname(dirname(createRequire(join(APP, 'package.json')).resolve('@cxxi-lab/hubbyware-ui')))
writeFileSync(join(WORK, 'tsconfig.ui.json'), JSON.stringify({
	compilerOptions: { target: 'ES2022', lib: ['ES2022', 'DOM', 'DOM.Iterable'], module: 'ESNext', moduleResolution: 'Bundler', jsx: 'react-jsx', strict: true, skipLibCheck: true, declaration: true, emitDeclarationOnly: true, rootDir: join(ui, 'src'), outDir: join(WORK, 'decl-ui') },
	include: [join(ui, 'src')]
}))
execFileSync(bin('tsc'), ['-p', join(WORK, 'tsconfig.ui.json')], { stdio: 'inherit' })
const entry = join(WORK, 'decl/frame/common.d.ts')
writeFileSync(join(WORK, 'tsconfig.json'), JSON.stringify({
	compilerOptions: { target: 'ES2022', module: 'ESNext', moduleResolution: 'Bundler', jsx: 'react-jsx', strict: true, skipLibCheck: true, baseUrl: WORK, paths: { '@cxxi-lab/hubbyware-ui': [join(WORK, 'decl-ui/index.d.ts')] } },
	files: [entry]
}))
const bundled = join(WORK, 'index.d.ts')
execFileSync(bin('dts-bundle-generator'), [
	'--project', join(WORK, 'tsconfig.json'), '--no-check', '--no-banner',
	'--external-imports', 'react', 'react-router', '@fortawesome/fontawesome-svg-core', '@fortawesome/free-solid-svg-icons', '@fortawesome/react-fontawesome', 'tailwind-variants',
	'-o', bundled, entry
], { stdio: 'inherit' })
const version = JSON.parse(readFileSync(resolve(APP, '../packages/hubbyware-sdk/version.json'), 'utf8')).version
const types = `// @cxxi-lab/hubbyware-sdk ${version}: generated by app/scripts/emit-sdk-types.mjs from packages/hubbyware-sdk/frame/common.ts — do not edit.\n${readFileSync(bundled, 'utf8')}`

if (CHECK) {
	const current = existsSync(OUT) ? readFileSync(OUT, 'utf8') : ''
	if (current !== types) {
		console.error('packages/hubbyware-sdk/types/index.d.ts is not up to date: run npm run types:sdk -w @hub/app')
		process.exit(1)
	}
	console.log('SDK types: up to date.')
}
else {
	writeFileSync(OUT, types)
	console.log(`SDK types → ${OUT}`)
}
