#!/usr/bin/env node
// The types of @cxxi-lab/hub-sdk (packages/hub-sdk/types/index.d.ts): the module contract as the app
// implements it (src/sdk/index.ts), in one declaration file, the design system and npm packages
// left as imports. A module's repository builds against them; at run time the host provides the SDK.
//   node scripts/emit-sdk-types.mjs           writes them
//   node scripts/emit-sdk-types.mjs --check   fails when they are not up to date (CI)
import { execFileSync } from 'node:child_process'
import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { createRequire } from 'node:module'

const APP = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const OUT = resolve(APP, '../packages/hub-sdk/types/index.d.ts')
const CHECK = process.argv.includes('--check')
// in the app (not in node_modules: the bundler would take it for a library), so the declarations
// find the packages (react…) as the sources do
const WORK = join(APP, '.cache/sdk-types')
const bin = name => join(APP, '../node_modules/.bin', name)

rmSync(WORK, { recursive: true, force: true })
mkdirSync(WORK, { recursive: true })
// 1. the app's declarations (its path aliases kept), 2. bundled from the SDK's entry
execFileSync(bin('tsc'), ['-p', join(APP, 'tsconfig.json'), '--noEmit', 'false', '--declaration', '--emitDeclarationOnly', '--rootDir', resolve(APP, '..'), '--outDir', join(WORK, 'decl')], { stdio: 'inherit' })
// (the design system apart: reached through node_modules, the app's emit leaves it out)
const ui = dirname(createRequire(join(APP, 'package.json')).resolve('@cxxi-lab/hub-ui/package.json'))
writeFileSync(join(WORK, 'tsconfig.ui.json'), JSON.stringify({
	compilerOptions: { target: 'ES2022', lib: ['ES2022', 'DOM', 'DOM.Iterable'], module: 'ESNext', moduleResolution: 'Bundler', jsx: 'react-jsx', strict: true, skipLibCheck: true, declaration: true, emitDeclarationOnly: true, rootDir: join(ui, 'src'), outDir: join(WORK, 'decl-ui') },
	include: [join(ui, 'src')]
}))
execFileSync(bin('tsc'), ['-p', join(WORK, 'tsconfig.ui.json')], { stdio: 'inherit' })
const decl = join(WORK, 'decl/app/src')
const aliases = JSON.parse(readFileSync(join(APP, 'tsconfig.json'), 'utf8')).compilerOptions.paths
const paths = Object.fromEntries(Object.entries(aliases)
	.filter(([alias]) => alias.startsWith('@') && !alias.startsWith('@cxxi-lab/') && alias !== '@preload')
	.map(([alias, [to]]) => [alias, [to.replace(/^src\//, '').replace(/\.ts$/, '')]]))
// the design system as declared too (an import left as it is, but its types read from there)
paths['@cxxi-lab/hub-ui'] = [join(WORK, 'decl-ui/index.d.ts')]
writeFileSync(join(WORK, 'tsconfig.json'), JSON.stringify({
	compilerOptions: { target: 'ES2022', module: 'ESNext', moduleResolution: 'Bundler', jsx: 'react-jsx', strict: true, skipLibCheck: true, baseUrl: decl, paths },
	files: [join(decl, 'sdk/index.d.ts')]
}))
const bundled = join(WORK, 'index.d.ts')
execFileSync(bin('dts-bundle-generator'), [
	'--project', join(WORK, 'tsconfig.json'), '--no-check', '--no-banner',
	'--external-imports', 'react', 'react-router', '@fortawesome/fontawesome-svg-core', '@fortawesome/free-solid-svg-icons', '@fortawesome/react-fontawesome', 'tailwind-variants',
	'-o', bundled, join(decl, 'sdk/index.d.ts')
], { stdio: 'inherit' })
const version = JSON.parse(readFileSync(resolve(APP, '../packages/hub-sdk/version.json'), 'utf8')).version
const types = `// @cxxi-lab/hub-sdk ${version}: generated by app/scripts/emit-sdk-types.mjs from app/src/sdk — do not edit.\n${readFileSync(bundled, 'utf8')}`

if (CHECK) {
	const current = existsSync(OUT) ? readFileSync(OUT, 'utf8') : ''
	if (current !== types) {
		console.error('packages/hub-sdk/types/index.d.ts is not up to date: run npm run types:sdk -w @hub/app')
		process.exit(1)
	}
	console.log('SDK types: up to date.')
}
else {
	writeFileSync(OUT, types)
	console.log(`SDK types → ${OUT}`)
}
